/* ---------- idioma ---------- */
let lang = localStorage.getItem('lang') || (navigator.language.startsWith('es') ? 'es' : 'en');
let current = 0;

function applyLang(l) {
  lang = l;
  const d = T[l];
  document.documentElement.lang = l;
  document.title = d.title;
  document.querySelector('meta[name="description"]').setAttribute('content', d.description);
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const k = el.dataset.i18n;
    if (d[k] !== undefined) el.innerHTML = d[k];
  });
  document.getElementById('lang-label').textContent = l === 'es' ? 'EN' : 'ES';
  localStorage.setItem('lang', l);
  buildTabs();
  renderMoment();
  stopBreath();
}
document.getElementById('lang-toggle').addEventListener('click', () => applyLang(lang === 'es' ? 'en' : 'es'));

/* ---------- momentos ---------- */
function buildTabs() {
  const tabs = document.getElementById('tabs');
  tabs.innerHTML = '';
  MOMENTS[lang].items.forEach((m, i) => {
    const b = document.createElement('button');
    b.type = 'button';
    b.className = 'tab';
    b.setAttribute('role', 'tab');
    b.setAttribute('aria-selected', i === current ? 'true' : 'false');
    b.innerHTML = `<span class="tab-n">0${i + 1}</span><span class="tab-t">${m.t}</span><span class="tab-d">${m.d}</span>`;
    b.addEventListener('click', () => { current = i; syncTabs(); renderMoment(true); });
    tabs.appendChild(b);
  });
}
function syncTabs() {
  document.querySelectorAll('.tab').forEach((b, i) => b.setAttribute('aria-selected', i === current ? 'true' : 'false'));
}
function renderMoment(animate) {
  const set = MOMENTS[lang];
  const m = set.items[current];
  const k = { task: set.task, host: set.host, ai: set.ai };
  const $ = (id) => document.getElementById(id);
  $('ov-title').textContent = m.title;
  $('ov-msg').textContent = m.msg(k);
  $('ov-adv-title').textContent = m.advT;
  $('ov-adv-body').textContent = m.advB(k);
  $('ov-input').textContent = m.input;
  $('ov-hint').textContent = m.hint;
  $('ov-back').textContent = m.back(k);
  $('ov-stay').textContent = m.stay;
  $('ov-breath').textContent = m.breath;
  if (animate) {
    const o = $('overlay');
    o.style.animation = 'none'; void o.offsetWidth; o.style.animation = '';
  }
}

/* ---------- respiración ---------- */
const PATTERNS = {
  '478': [[4, 'in'], [7, 'hold'], [8, 'out']],
  box: [[4, 'in'], [4, 'hold'], [4, 'out'], [4, 'hold']],
  '55': [[5, 'in'], [5, 'out']],
};
const WORDS = {
  es: { in: 'Inhala', hold: 'Mantén', out: 'Exhala' },
  en: { in: 'Inhale', hold: 'Hold', out: 'Exhale' },
};
const orbBtn = document.getElementById('orb');
const orb = orbBtn.querySelector('.orb');
const phaseEl = document.getElementById('phase');
const countEl = document.getElementById('count');
const hintEl = document.getElementById('breath-hint');
let pattern = '478';
let timer = null;
let running = false;
let scale = 0.62;

function setScale(s, secs) {
  scale = s;
  orb.style.transitionDuration = secs + 's';
  orb.style.transform = `scale(${s})`;
}
function stopBreath() {
  clearTimeout(timer);
  running = false;
  orbBtn.dataset.run = '0';
  phaseEl.textContent = T[lang]['breath.idle'];
  countEl.textContent = '';
  hintEl.textContent = T[lang]['breath.hint'];
  setScale(0.62, 1.2);
}
function startBreath() {
  running = true;
  orbBtn.dataset.run = '1';
  hintEl.textContent = T[lang]['breath.stop'];
  let phaseIdx = 0;
  let cycle = 1;
  const runPhase = () => {
    const steps = PATTERNS[pattern];
    const [secs, kind] = steps[phaseIdx];
    phaseEl.textContent = WORDS[lang][kind];
    if (kind === 'in') setScale(1, secs);
    if (kind === 'out') setScale(0.62, secs);
    let left = secs;
    const tick = () => {
      countEl.textContent = left;
      if (left === 0) {
        phaseIdx = (phaseIdx + 1) % steps.length;
        if (phaseIdx === 0) { cycle += 1; }
        hintEl.textContent = `${T[lang]['breath.stop']} · ${T[lang]['breath.cycle']} ${cycle}`;
        runPhase();
        return;
      }
      left -= 1;
      timer = setTimeout(tick, 1000);
    };
    tick();
  };
  runPhase();
}
orbBtn.addEventListener('click', () => (running ? stopBreath() : startBreath()));
document.querySelectorAll('.pat').forEach((b) => b.addEventListener('click', () => {
  document.querySelectorAll('.pat').forEach((x) => { x.classList.remove('is-on'); x.setAttribute('aria-pressed', 'false'); });
  b.classList.add('is-on'); b.setAttribute('aria-pressed', 'true');
  pattern = b.dataset.pat;
  stopBreath();
}));

applyLang(lang);
