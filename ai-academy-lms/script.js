let lang = localStorage.getItem('lang') || (navigator.language.startsWith('es') ? 'es' : 'en');

function applyLang(l) {
  lang = l;
  const d = T[l];
  document.documentElement.lang = l;
  document.title = d.title;
  document.querySelector('meta[name="description"]').setAttribute('content', d.description);
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const k = el.dataset.i18n;
    if (d[k] !== undefined) el.innerHTML = d[k];
  });
  document.getElementById('lang-label').textContent = l === 'es' ? 'EN' : 'ES';
  localStorage.setItem('lang', l);
}
document.getElementById('lang-toggle').addEventListener('click', () => applyLang(lang === 'es' ? 'en' : 'es'));
applyLang(lang);

/* índice: capítulo activo al hacer scroll */
const links = [...document.querySelectorAll('#toc a')];
const sections = [...document.querySelectorAll('.page[data-sec]')];
const setOn = (id) => links.forEach((a) => a.classList.toggle('on', a.dataset.sec === id));
const io = new IntersectionObserver((entries) => {
  entries.forEach((e) => { if (e.isIntersecting) setOn(e.target.dataset.sec); });
}, { rootMargin: '-35% 0px -55% 0px' });
sections.forEach((s) => io.observe(s));
setOn('portada');

/* home: resaltar la zona del esquema ↔ la nota */
const zones = [...document.querySelectorAll('#wf [data-z]')];
const notes = [...document.querySelectorAll('#notes li')];
const light = (z, on) => {
  zones.filter((e) => e.dataset.z === z).forEach((e) => e.classList.toggle('on', on));
  notes.filter((e) => e.dataset.z === z).forEach((e) => e.classList.toggle('on', on));
};
[...zones, ...notes].forEach((el) => {
  if (el.tagName === 'LI') el.tabIndex = 0;
  el.addEventListener('mouseenter', () => light(el.dataset.z, true));
  el.addEventListener('mouseleave', () => light(el.dataset.z, false));
  el.addEventListener('focus', () => light(el.dataset.z, true));
  el.addEventListener('blur', () => light(el.dataset.z, false));
});
